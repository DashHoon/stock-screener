def sector_of(industry: str | None, code: str | None = None) -> str:
    """업종명 → 섹터명. 종목코드가 OVERRIDE에 있으면 그쪽이 우선한다."""
    if code and code in OVERRIDE:
        return OVERRIDE[code]
    if not industry:
        return ETC
    return SECTOR_OF.get(industry.strip(), ETC)
